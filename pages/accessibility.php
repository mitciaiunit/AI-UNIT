      <p tabindex="0">This website offers a simple language mode that replaces longer passages with short, plain-language summaries. Summaries are written and reviewed by the AI Unit. They are a guide, not the authoritative text - turn Simple language off in the navbar at any time to see the original full text again, and the official policy documents remain available in full from the Framework Library. Simple language mode is never switched on automatically - it is always the visitor's choice.</p>
